"""The text of ``AUDIT.md``: both parts of design section 9, from the results that ``rule_audit.py`` collects.

This module only renders. It runs no check and calls no model. ``rule_audit.build_report`` gives it plain dicts, so a part
with no data is a dict with a ``status`` and a ``reason``, and the text says why.

It also says which kind of numbers a report shows (``basis_of``). That comes from the ``policies`` section of
``sets/registry.json`` (generated by ``sets/build_registry.py``), and from nothing else: a policy that no set and no
change names is ``unseen, no run``, and a policy whose only sets have been run by an agent model is ``seen, not tuned``,
never ``held-out``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

HERE = Path(__file__).resolve().parent
REGISTRY = HERE / "sets" / "registry.json"
LAYERS = ("schema", "code", "cedar", "verifier")


# -- which kind of numbers --------------------------------------------------------------------------------------------


def basis_of(
    bench: str, policy: str, build: str, override: str = "", registry: Optional[Path] = None
) -> Tuple[str, str]:
    """``(kind, why)``. Kind: ``tuning`` (a set used for tuning has a task of this policy, or a change fixed the pipeline on
    it); ``seen, not tuned`` (only held-out sets name it, and an agent model has run at least one of them: the tasks and their
    failures are known); ``held-out`` (only held-out sets name it and no model has run any of them: nothing now); ``unseen, no
    run`` (no set and no change names it). A ``gold`` build says both: that it is the reference build, and what kind its policy
    is. A set that some model has run (``seen_n`` above 0 for any model) is never ``held-out``."""
    if override:
        return override, "set with --basis"
    path = registry or REGISTRY
    if not path.is_file():
        return "unseen, no run", f"{path.name} is not there, so nothing says whether this policy was used"
    data = json.loads(path.read_text(encoding="utf-8"))
    found = (data.get("policies") or {}).get(f"{bench}/{policy}")
    sets = {s["id"]: s for s in data.get("sets") or []}
    nothing = "no task set and no change names this policy in the `policies` section of the registry"
    if found is None:
        kind, why = "unseen, no run", nothing
    else:
        tuning, held = found.get("tuning_sets") or [], found.get("heldout_sets") or []
        changes = found.get("tuned_by_changes") or []
        facts = []
        if tuning:
            facts.append("tuning sets " + ", ".join(tuning))
        if changes:
            facts.append("the pipeline was repaired on it in changes " + ", ".join(map(str, changes)))
        if held:
            facts.append("held-out sets " + ", ".join(f"{h} ({_seen_text(sets.get(h))})" for h in held))
        if tuning or changes:
            kind = "tuning"
            why = "; ".join(facts) + (
                "; the held-out tasks of this policy are not independent of its tuning" if held else ""
            )
        elif held:
            seen = [h for h in held if h not in sets or any(n > 0 for n in sets[h]["seen_n"].values())]
            kind = "seen, not tuned" if seen else "held-out"
            why = "; ".join(facts) + " (no tuning set and no change names it)"
        else:  # a note and nothing else: no set and no change has used it
            kind, why = "unseen, no run", nothing
        if found.get("note"):
            why += f". Note: {found['note']}"
    if build == "gold":
        return f"gold, {kind}", f"this is the reference build of the policy. The policy: {why}"
    return kind, why


def _seen_text(entry: Optional[Dict[str, Any]]) -> str:
    """Which agent models ran the tasks of a set, for the note of a label."""
    if entry is None:
        return "not in the registry, so taken as seen"
    ran = sorted(m for m, n in entry["seen_n"].items() if n > 0)
    return "run by " + ", ".join(ran) if ran else "run by no agent model"


# -- tables -----------------------------------------------------------------------------------------------------------


def _table(head: List[str], rows: List[List[Any]]) -> List[str]:
    return [
        "| " + " | ".join(head) + " |",
        "|" + "|".join("---" for _ in head) + "|",
        *["| " + " | ".join(str(c) for c in r) + " |" for r in rows],
        "",
    ]


def _counts(d: Dict[str, Any]) -> str:
    return ", ".join(f"{k} {v}" for k, v in d.items()) or "none"


def _of(shown: int, total: int, what: str) -> str:
    return f"Showing {shown} of {total} {what}." if shown < total else ""


# -- part 1 -----------------------------------------------------------------------------------------------------------


def _static_rows(st: Dict[str, Any]) -> List[List[Any]]:
    cov, val, cf = st["coverage"], st["validator"], st["conflicts"]
    rows: List[List[Any]] = []
    if cov["statements"]:
        must = sum(n for k, n in cov["by_modality"].items() if k in ("must", "must_not"))
        rows.append(
            [
                "Coverage",
                f"{cov['without_outcome']} of {must} must or must-not statements have no outcome ({cov['statements']} statements)",
                f"coverage items: {_counts(cov['coverage_items'])}; policy questions: {cov['policy_questions']}",
            ]
        )
    else:
        rows.append(
            [
                "Coverage",
                "no data",
                "the package holds no policy text (`documents` is empty), so statements cannot be counted",
            ]
        )
    text_note = (
        f"source text: the statements of package `{st['text_from']}` of the same policy"
        if st.get("text_from")
        else "source text: the package's own"
    )
    if not st["rules"]:
        rows.append(
            ["Values grounded, rules that never fire, unknown tool", "no data", "the package has no rules"]
        )
    elif st["grounding"] == "no text":
        rows.append(
            [
                "Values grounded in the source",
                "no data",
                "no policy text in the package or in any package of the same policy",
            ]
        )
    else:
        rows.append(
            [
                "Values grounded in the source",
                f"{st['ungrounded_values']} of {st['grounded_checked']} rules have a value not found in their source text",
                f"{text_note}; {st['no_source']} rules have no source text and are not counted",
            ]
        )
    if st["rules"]:
        rows.append(["Rules that can never fire", f"{st['never_fire']} (no trigger tool)", ""])
        known = st["unknown_tool"] is not None
        rows.append(
            [
                "Unknown tool",
                f"{st['unknown_tool']}" if known else "no data",
                "" if known else "no tool specs given",
            ]
        )
    rows.append(
        [
            "`validate_package`",
            f"{val['errors']} errors, {val['warnings']} warnings",
            f"mode: {val['mode']}; " + (_counts(val["by_code"]) if val["by_code"] else "no finding"),
        ]
    )
    errors = sum(c["severity"] == "error" for c in cf)
    shown = "; ".join(c["message"].split(";")[0][:140] for c in cf[:2])
    rows.append(
        [
            "`rule_conflict`",
            f"{len(cf)} (errors {errors}, warnings {len(cf) - errors})",
            shown + (f" ({_of(min(2, len(cf)), len(cf), 'conflicts')})" if len(cf) > 2 else ""),
        ]
    )
    return rows


def _cedar_rows(ce: Dict[str, Any]) -> List[List[Any]]:
    if ce.get("status") != "ok":
        return [["Cedar validator and batch check", "no data", ce.get("reason", "")]]
    v = ce["validator"]
    return [
        [
            "Cedar validator",
            "passed" if v["passed"] else f"FAILED: {'; '.join(v['errors'][:2])}",
            f"{ce['role_rules']} role rules",
        ],
        [
            "Cedar against the rule JSON",
            f"{ce['differences']} of {ce['requests']} requests differ",
            f"{len(ce['roles'])} roles x {ce['tools']} tools",
        ],
    ]


def _backtrans_row(bt: Optional[Dict[str, Any]], why: str) -> List[Any]:
    if not bt:
        return ["Back-translation", "no data", why]
    if bt.get("status") != "ok":
        return ["Back-translation", "no data", bt.get("reason", "")]
    c = bt["counts"]
    judged = bt["judged"]
    rest = ", ".join(f"{k} {v}" for k, v in sorted(c.items()) if k != "equivalent")
    return [
        "Back-translation",
        f"{c.get('equivalent', 0)} of {judged} equivalent" + (f"; {rest}" if rest else ""),
        f"source text of the judged rules: {_counts(bt['source_kinds'])}"
        + (
            f", from package `{bt['text_from']}` of the same policy"
            if bt["text_from"] != "the package"
            else ""
        )
        + (f"; {bt['not_judged']} rules with no source text not judged" if bt["not_judged"] else "")
        + f"; writer {bt['writer']}, judge {bt['judge']} (another model family); not reviewed by a person; {bt['file']}",
    ]


def _tests_section(
    tr: Dict[str, Any], vruns: List[Dict[str, Any]], stale: List[str], failed_statements: int
) -> List[str]:
    out = ["### Decision tests, through all layers", ""]
    if tr.get("status") != "ok":
        return out + [f"No data: {tr.get('reason', tr.get('status'))}.", ""]
    s = tr["summary"]
    out += [
        f"{tr['cases']} tests from {tr['tests_from']}: {s['deny_cases']} should be denied, {s['allow_cases']} should be allowed. "
        "Caught = deny or remind by a rule, plus the calls the tool's own schema rejects.",
        "",
    ]
    if failed_statements:
        out += [
            f"The tests were written with {failed_statements} statements that failed (recorded in the package): they have no test.",
            "",
        ]
    head = [
        "Run",
        "Caught",
        "of which tool schema",
        "of which only the schema",
        "False denies",
        "False reminders",
        "Errors",
        "Failed verifier calls",
    ]
    rows = [
        [
            "code and Cedar, no model",
            f"{s['caught']} of {s['deny_cases']}",
            s["caught_by_schema"],
            s["caught_only_by_schema"],
            f"{s['false_deny']} of {s['allow_cases']}",
            f"{s['false_remind']} of {s['allow_cases']}",
            s["errors"],
            "-",
        ]
    ]
    for v in vruns:
        vs = v["summary"]
        rows.append(
            [
                f"+ verifier {v['verifier']} ({v['ran_at'][:16]} UTC"
                + (f", {v['seconds']} s)" if "seconds" in v else ")"),
                f"{vs['caught']} of {vs['deny_cases']}",
                vs["caught_by_schema"],
                vs["caught_only_by_schema"],
                f"{vs['false_deny']} of {vs['allow_cases']}",
                f"{vs['false_remind']} of {vs['allow_cases']}",
                vs["errors"],
                vs.get("verifier_errors", 0),
            ]
        )
    out += _table(head, rows)
    if len(vruns) > 1:
        first = vruns[0]["rows"]
        differ = [sum(_key(a) != _key(b) for a, b in zip(first, v["rows"])) for v in vruns[1:]]
        spread = [
            f"{name} {min(v['summary'][key] for v in vruns)} to {max(v['summary'][key] for v in vruns)}"
            for key, name in (
                ("caught", "caught"),
                ("false_remind", "false reminders"),
                ("false_deny", "false denies"),
            )
        ]
        out += [
            f"Verifier spread over {len(vruns)} runs: {'; '.join(spread)}. Rows that differ from the first run: "
            f"{', '.join(map(str, differ))} of {len(first)}. A run made right after another is answered partly from the "
            "gateway's cache (it takes a fraction of the time), so this spread is a lower bound; it is one sample, not a range.",
            "",
        ]
    if stale:
        out += [
            f"Left out, a saved result of another package version or another test set: {', '.join(stale)}.",
            "",
        ]
    out += [
        "By layer, code-only run (a case can be caught by more than one layer; the verifier layer is empty without "
        f"`--verifier`). {s['schema_on_allow']} allow tests are rejected by the tool schema itself; they are not counted as false denies.",
        "",
    ]
    rows = [
        [layer]
        + [
            "-" if s["layers"][layer][k] is None else s["layers"][layer][k]
            for k in ("caught", "caught_deny", "false_deny", "false_remind")
        ]
        for layer in LAYERS
    ]
    return out + _table(
        ["Layer", "Caught (deny or remind)", "of which deny", "False denies", "False reminders"], rows
    )


def _key(row: Dict[str, Any]) -> Tuple[Any, ...]:
    return (row["decision"], tuple(sorted(f["rule"] or "" for f in row["fired"])))


# -- part 2 -----------------------------------------------------------------------------------------------------------


def _skipped(counts: Dict[str, int]) -> str:
    """The reasons runs were left out. Runs of other policies are one line: how many, and of how many policies."""
    other = [(k, v) for k, v in counts.items() if k.startswith("other policy (")]
    parts = [f"{k} {v}" for k, v in counts.items() if not k.startswith("other policy (")]
    if other:
        parts.insert(0, f"other policy {sum(v for _, v in other)} (of {len(other)} policies)")
    return ", ".join(parts) or "none"


def _part2(rp: Dict[str, Any], has_role_rules: bool) -> List[str]:
    out = ["## Part 2: fidelity to use", ""]
    if rp.get("status") != "ok":
        return out + [f"No data: {rp.get('reason', rp.get('status'))}.", ""]
    skipped = _skipped(rp["skipped"])
    out += [
        f"{rp['runs_read']} runs read; skipped: {skipped}. `replayed`: the tool calls of the run go through this package's code and "
        "Cedar checks. `live`: the decisions that a harness run met, from its `audit.jsonl`, when its result names this package version.",
        "",
        f"Role of the logged-in user, runs by source: {_counts(rp['role_sources'])}."
        + (
            " The default is `admin`, which no role rule forbids: with role rules in the package, the reminders and denies of those rules are "
            "undercounted for every run on the default."
            if has_role_rules and rp["role_sources"].get("default admin")
            else ""
        ),
        "",
    ]
    if rp.get("errors"):
        out += [f"{rp['errors']} calls made a rule raise an error; the call counts as allowed.", ""]
    rows = []
    for name in ("replayed", "live"):
        s = rp[name]
        if not s["runs"]:
            rows.append([name, "no data", "", "", "", "", ""])
            continue
        rows.append(
            [
                name,
                f"{s['runs']} ({s['passed_runs']} passed)",
                f"{s['passed_runs_with_deny']} of {s['passed_runs']}",
                f"{s['passed_runs_with_remind']} of {s['passed_runs']}",
                f"{s['failed_runs_with_deny']} of {s['runs'] - s['passed_runs']}",
                f"{s['denies_on_passed']} / {s['denies_on_failed']}",
                f"{s['reminds_on_passed']} / {s['reminds_on_failed']}",
            ]
        )
    out += _table(
        [
            "Source",
            "Runs",
            "Passed runs with a deny",
            "Passed runs with a reminder (false reminders)",
            "Failed runs with a deny",
            "Denies on passed / failed",
            "Reminders on passed / failed",
        ],
        rows,
    )
    for name in ("replayed", "live"):
        rules = sorted(
            rp[name]["by_rule"].items(),
            key=lambda kv: -sum(v for k, v in kv[1].items() if k.startswith(("deny_", "remind_"))),
        )
        if rules:
            out += [f"### Denies and reminders per rule ({name})", ""]
            out += _table(
                [
                    "Rule",
                    "Type",
                    "Source",
                    "Deny, passed runs",
                    "Deny, failed runs",
                    "Remind, passed runs",
                    "Remind, failed runs",
                ],
                [
                    [
                        r,
                        v["type"],
                        v["source"],
                        v["deny_on_passed"],
                        v["deny_on_failed"],
                        v["remind_on_passed"],
                        v["remind_on_failed"],
                    ]
                    for r, v in rules[:12]
                ],
            )
            if _of(12, len(rules), "rules"):
                out += [_of(12, len(rules), "rules"), ""]
    out += ["### Conflicts with graders (rules that denied on a passed run)", ""]
    conflicts = rp["conflicts_with_graders"]
    if not conflicts:
        return out + ["None.", ""]
    out += _table(
        ["Rule", "Type", "Source", "Denies on passed runs", "From", "Tasks"],
        [
            [
                c["rule"],
                c["type"],
                c["source"],
                c["deny_on_passed"],
                c["from"],
                ", ".join(c["denied_passed_tasks"][:3]),
            ]
            for c in conflicts[:15]
        ],
    )
    if _of(15, len(conflicts), "conflicts"):
        out += [_of(15, len(conflicts), "conflicts"), ""]
    return out


# -- the whole report -------------------------------------------------------------------------------------------------


def render(info: Dict[str, Any]) -> str:
    """``info``: label, version_id, generator, today, counts (rules, procedures, obligations, tests, failed_statements),
    basis (kind, why), static, tests, verifier_runs, stale, cedar, backtrans, backtrans_reason, replay, note."""
    gen = info["generator"] or {}
    n = info["counts"]
    kind, why = info["basis"]
    out = [
        f"# Audit of {info['label']}",
        "",
        f"Made on {info['today']} by `rule_audit.py report`. Package version `{info['version_id']}`; "
        f"made by {gen.get('kind', '?')} / {gen.get('harness', '?')} / {gen.get('model', '?')}. "
        f"{n['rules']} rules, {n['procedures']} procedures, {n['obligations']} obligations, {n['tests']} decision tests in the package.",
        "",
        "## Which numbers these are",
        "",
        f"**{kind}**: {why}.",
        "",
        "The checks use no model unless a line names one. Back-translation and verifier numbers are read from saved results.",
        "",
    ]
    if info.get("note"):
        out += [f"Note: {info['note']}", ""]
    out += ["## Part 1: fidelity to the text", ""]
    rows = (
        _static_rows(info["static"])
        + _cedar_rows(info["cedar"])
        + [_backtrans_row(info["backtrans"], info["backtrans_reason"])]
    )
    out += _table(["Check", "Result", "Note"], rows)
    out += _tests_section(info["tests"], info["verifier_runs"], info["stale"], n["failed_statements"])
    out += _part2(info["replay"], info["static"]["cedar_rules"] > 0)
    return "\n".join(out).rstrip() + "\n"
