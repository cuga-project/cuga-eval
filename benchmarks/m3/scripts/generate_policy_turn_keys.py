#!/usr/bin/env python3
"""Generate --eval-key TOML entries for policy/turn-count breakdowns.

Reads an M3 ``--m3-data`` corpus (zip or directory) and prints TOML array
entries partitioning its samples by whether they carry a policy
(``additional_instructions`` non-empty) and by turn count (single- vs
multi-turn), plus any pairwise intersection that isn't degenerate (empty, or
identical to one of the four base buckets — which happens whenever policy is
collinear with turn count in the source data). Paste the output into
``benchmarks/m3/eval_config.toml`` under a comment block naming the source.

Usage:
    uv run python benchmarks/m3/scripts/generate_policy_turn_keys.py \\
        --m3-data benchmarks/m3/data/capability_4_multiturn_policy_sampled.zip \\
        --prefix cap4
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List

_REPO_ROOT = Path(__file__).resolve().parents[3]
_DEFAULT_DATA = _REPO_ROOT / "benchmarks" / "m3" / "data" / "capability_4_multiturn_policy_sampled.zip"

if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from benchmarks.m3.m3_data_loader import M3DataLoader  # noqa: E402

_BASE_KEYS = ("single_turn", "multi_turn", "with_policy", "without_policy")
_INTERSECTION_KEYS = (
    "single_turn_with_policy",
    "single_turn_without_policy",
    "multi_turn_with_policy",
    "multi_turn_without_policy",
)


def collect_ids(data_path: Path) -> Dict[str, List[str]]:
    loader = M3DataLoader(data_path, allow_missing_output=True)

    buckets: Dict[str, List[str]] = {k: [] for k in _BASE_KEYS + _INTERSECTION_KEYS}

    for task_id, domain in loader.available_pairs():
        for sample in loader.load_domain(task_id, domain):
            sid = str(sample["sample_id"])
            is_single = sample.get("num_turns") == 1
            has_policy = bool(str(sample.get("additional_instructions") or "").strip())

            turn_key = "single_turn" if is_single else "multi_turn"
            policy_key = "with_policy" if has_policy else "without_policy"
            buckets[turn_key].append(sid)
            buckets[policy_key].append(sid)
            buckets[f"{turn_key}_{policy_key}"].append(sid)

    return buckets


def drop_degenerate(buckets: Dict[str, List[str]]) -> Dict[str, List[str]]:
    """Keep the four base buckets; drop intersections that are empty or identical
    (as a set) to a base bucket — i.e. add no information beyond what
    single_turn/multi_turn/with_policy/without_policy already say.
    """
    base_sets = {frozenset(buckets[k]) for k in _BASE_KEYS}
    kept = {k: buckets[k] for k in _BASE_KEYS}
    for k in _INTERSECTION_KEYS:
        ids = buckets[k]
        if ids and frozenset(ids) not in base_sets:
            kept[k] = ids
    return kept


def _toml_string_array(values: List[str]) -> str:
    if not values:
        return "[]"
    lines = ",\n".join(f'  "{v}"' for v in sorted(values))
    return f"[\n{lines},\n]"


def render_toml(buckets: Dict[str, List[str]], *, source: str, prefix: str) -> str:
    counts = "\n".join(f"#   {prefix}_{name}: {len(ids)}" for name, ids in buckets.items())
    header = f"""\
# Policy / turn-count breakdown for {source}, generated by
# benchmarks/m3/scripts/generate_policy_turn_keys.py.
#
# Counts:
{counts}
"""
    body_parts = [f"{prefix}_{name} = {_toml_string_array(ids)}\n" for name, ids in buckets.items()]
    return header + "\n" + "\n".join(body_parts)


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--m3-data",
        type=Path,
        default=_DEFAULT_DATA,
        help=f"Path to an M3 data zip or directory (default: {_DEFAULT_DATA.relative_to(_REPO_ROOT)})",
    )
    parser.add_argument(
        "--prefix",
        default="cap4",
        help="Prefix for generated eval-key names, e.g. 'cap4' -> cap4_single_turn (default: cap4)",
    )
    args = parser.parse_args(argv)

    buckets = drop_degenerate(collect_ids(args.m3_data))

    try:
        source_display = str(args.m3_data.resolve().relative_to(_REPO_ROOT))
    except ValueError:
        source_display = str(args.m3_data)

    print(render_toml(buckets, source=source_display, prefix=args.prefix))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
