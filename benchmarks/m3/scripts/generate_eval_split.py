#!/usr/bin/env python3
"""Generate ``benchmarks/m3/eval_config.toml``: a reproducible train/test split.

Reads an M3 ``--m3-data`` corpus (zip or directory, same layout understood by
``M3DataLoader``) and writes a TOML file mapping split names (``train`` /
``test``) to lists of sample UUIDs. The split is computed independently for
each ``(task_id, domain)`` group so every group is represented in both splits
("stratified" by capability/domain).

The resulting file is consumed by ``benchmarks/m3/eval_config_loader.py`` and
the ``--eval-key`` flag of ``eval_m3.py`` / ``eval_m3_react.py``.

Usage:
    uv run python benchmarks/m3/scripts/generate_eval_split.py
    uv run python benchmarks/m3/scripts/generate_eval_split.py --ratio 0.6 --seed 7 \\
        --m3-data benchmarks/m3/data/small_train.zip --output benchmarks/m3/eval_config.toml
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path
from typing import Dict, List, Tuple

_REPO_ROOT = Path(__file__).resolve().parents[3]
_DEFAULT_DATA = _REPO_ROOT / "benchmarks" / "m3" / "data" / "small_train.zip"
_DEFAULT_OUTPUT = _REPO_ROOT / "benchmarks" / "m3" / "eval_config.toml"

if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from benchmarks.m3.m3_data_loader import M3DataLoader  # noqa: E402

GroupCounts = Dict[Tuple[int, str], Tuple[int, int]]


def split_ids(data_path: Path, ratio: float, seed: int) -> Tuple[List[str], List[str], GroupCounts]:
    """Split every ``(task_id, domain)`` group's sample ids into train/test.

    Each group is shuffled with a seed derived from ``(seed, task_id, domain)``
    so the split is reproducible and independent of group iteration order.
    Returns the combined train ids, combined test ids, and per-group
    ``(train_count, test_count)`` for provenance reporting.
    """
    loader = M3DataLoader(data_path, allow_missing_output=True)

    train_ids: List[str] = []
    test_ids: List[str] = []
    counts: GroupCounts = {}

    for task_id, domain in loader.available_pairs():
        samples = loader.load_domain(task_id, domain)
        ids = [str(s["sample_id"]) for s in samples]

        rng = random.Random(f"{seed}:{task_id}:{domain}")  # noqa: S311
        shuffled = ids[:]
        rng.shuffle(shuffled)

        split_idx = round(len(shuffled) * ratio)
        group_train, group_test = shuffled[:split_idx], shuffled[split_idx:]

        train_ids.extend(group_train)
        test_ids.extend(group_test)
        counts[(task_id, domain)] = (len(group_train), len(group_test))

    return train_ids, test_ids, counts


def _toml_string_array(values: List[str]) -> str:
    if not values:
        return "[]"
    lines = ",\n".join(f'  "{v}"' for v in sorted(values))
    return f"[\n{lines},\n]"


def render_toml(
    train_ids: List[str],
    test_ids: List[str],
    counts: GroupCounts,
    *,
    source: str,
    ratio: float,
    seed: int,
    eval_key: str | None,
) -> str:
    group_lines = "\n".join(
        f"#   task_{task_id}/{domain}: {train_n} train / {test_n} test"
        for (task_id, domain), (train_n, test_n) in sorted(counts.items())
    )

    header = f"""\
# M3 evaluation task-set definitions, used by --eval-key.
#
# Generated by benchmarks/m3/scripts/generate_eval_split.py:
#   source: {source}
#   ratio:  {ratio} (train fraction)
#   seed:   {seed}
#
# Each list below holds M3 sample UUIDs (M3DataLoader's `sample_id`/`uuid`
# field). Pass --eval-key <name> to eval_m3.py / eval_m3_react.py to restrict
# an --m3-data run to one of these sets. The filter is applied per-domain,
# before --task/--domain/--capability filters.
#
# Per-(task_id, domain) split sizes:
{group_lines}
#
# Totals: {len(train_ids)} train / {len(test_ids)} test
"""

    body = f"""
train = {_toml_string_array(train_ids)}

test = {_toml_string_array(test_ids)}
"""

    if eval_key:
        body += f'\n# Default split used when --eval-key is omitted.\neval_key = "{eval_key}"\n'

    return header + body


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--m3-data",
        type=Path,
        default=_DEFAULT_DATA,
        help=f"Path to an M3 data zip or directory (default: {_DEFAULT_DATA.relative_to(_REPO_ROOT)})",
    )
    parser.add_argument(
        "--ratio",
        type=float,
        default=0.5,
        help="Train fraction per (task_id, domain) group, e.g. 0.5 for 50/50 or 0.6 for 60/40 (default: 0.5)",
    )
    parser.add_argument("--seed", type=int, default=42, help="Random seed for the split (default: 42)")
    parser.add_argument(
        "--output",
        type=Path,
        default=_DEFAULT_OUTPUT,
        help=f"Output TOML path (default: {_DEFAULT_OUTPUT.relative_to(_REPO_ROOT)})",
    )
    parser.add_argument(
        "--eval-key",
        choices=["train", "test"],
        default=None,
        help="If set, write this split name as the default `eval_key` used when --eval-key is omitted",
    )
    args = parser.parse_args(argv)

    if not 0.0 < args.ratio < 1.0:
        parser.error("--ratio must be between 0 and 1 (exclusive)")

    train_ids, test_ids, counts = split_ids(args.m3_data, args.ratio, args.seed)

    train_set, test_set = set(train_ids), set(test_ids)
    overlap = train_set & test_set
    if overlap:
        raise RuntimeError(f"train/test overlap detected ({len(overlap)} ids): {sorted(overlap)[:5]}...")

    expected_total = sum(train_n + test_n for train_n, test_n in counts.values())
    actual_total = len(train_ids) + len(test_ids)
    if actual_total != expected_total:
        raise RuntimeError(f"sample count mismatch: expected {expected_total}, got {actual_total}")

    try:
        source_display = str(args.m3_data.resolve().relative_to(_REPO_ROOT))
    except ValueError:
        source_display = str(args.m3_data)

    toml_text = render_toml(
        train_ids,
        test_ids,
        counts,
        source=source_display,
        ratio=args.ratio,
        seed=args.seed,
        eval_key=args.eval_key,
    )
    args.output.write_text(toml_text, encoding="utf-8")

    print(f"Wrote {len(train_ids)} train / {len(test_ids)} test sample id(s) to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
